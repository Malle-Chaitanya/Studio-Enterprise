/** One tile per connector: a real official mark where Simple Icons has one,
 *  a hand-approximated (but real-color) mark for the handful of enterprise
 *  brands it doesn't carry, otherwise a tinted initials tile so nothing ever
 *  renders blank. */
export function ConnectorMark({ connectorId, name, emojiHint }: {
  connectorId: string;
  name: string;
  /** The registry's own `icon` field (an emoji) — used only to tint the fallback. */
  emojiHint?: string;
}) {
  const official = OFFICIAL_MARKS[connectorId];
  if (official) {
    return (
      <svg viewBox={official.viewBox ?? '0 0 24 24'} role="img" aria-label={name}>
        <rect x="0" y="0" width="24" height="24" rx="5" fill={`#${official.hex}`} />
        <path d={official.d} fill="#fff" transform="translate(3.6 3.6) scale(0.7)" />
      </svg>
    );
  }
  const Approx = APPROX_MARKS[connectorId];
  if (Approx) return <Approx />;
  const tint = (emojiHint && EMOJI_TINT[emojiHint]) || '#0129AC';
  return (
    <svg viewBox="0 0 24 24" role="img" aria-label={name}>
      <rect x="2" y="2" width="20" height="20" rx="5" fill={tint} />
      <text x="12" y="16" fontSize="10" fontWeight="700" textAnchor="middle" fill="#fff">
        {name.slice(0, 2).toUpperCase()}
      </text>
    </svg>
  );
}
